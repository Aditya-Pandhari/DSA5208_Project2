"""Generate the Dataproc copy of the notebook from the submitted one.

    python cloud/make_dataproc_notebook.py        # writes cloud/full_run/DSA5208_Project2_dataproc.ipynb

The analysis code is unchanged; only what a cluster needs differently is changed:
  * Spark master: YARN (env SPARK_MASTER, default "yarn") instead of local[*]; no loopback driver binding.
  * Storage: the notebook's paths are absolute paths without a scheme, so on Dataproc Spark resolves them on HDFS
    (the run directory is /tmp/dsa5208 locally and on HDFS); disk sizes are measured on HDFS as well.
  * Section 20 (wall time against laptop cores) is omitted: it benchmarks local[n] sessions on one machine.
  * The environment table also records the CPU model on Linux and the cluster description.
Outputs are stripped; master_run.sh executes the generated notebook on the cluster.
"""
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "DSA5208_Project2.ipynb"
OUT = REPO / "cloud" / "full_run" / "DSA5208_Project2_dataproc.ipynb"

nb = json.loads(SRC.read_text())
cells = nb["cells"]
text = lambda c: "".join(c["source"])


def set_text(c, s):
    c["source"] = s.splitlines(keepends=True)


def replace_in(match, old, new, count=1):
    hits = [c for c in cells if match in text(c)]
    assert len(hits) == 1, f"{len(hits)} cells match {match!r}"
    s = text(hits[0])
    assert s.count(old) == count, f"{old!r} found {s.count(old)} times"
    set_text(hits[0], s.replace(old, new))


# ---- Spark session: YARN, no loopback binding, YARN manages local dirs ------------------------
replace_in("SparkSession.builder.appName(\"dsa5208-rainfall\")",
           "SPARK_MASTER = f\"local[{os.environ.get('SPARK_LOCAL_CORES', '*')}]\"",
           "SPARK_MASTER = os.environ.get(\"SPARK_MASTER\", \"yarn\")      # Dataproc: the YARN cluster manager")
for line in ['    .config("spark.driver.bindAddress", "127.0.0.1")   # a Wi-Fi change or sleep/wake cannot break block transfers\n',
             '    .config("spark.driver.host", "127.0.0.1")\n',
             '    .config("spark.local.dir", os.environ.get("SPARK_LOCAL_DIR", "/tmp/spark-tmp"))\n']:
    replace_in("SparkSession.builder.appName(\"dsa5208-rainfall\")", line, "")

# ---- disk sizes: local files plus the HDFS copy of the same path -----------------------------
replace_in("def du(path):",
           '''def du(path):
    """Size of a file or directory tree in MB."""
    p = Path(path)
    files = [p] if p.is_file() else [f for f in p.rglob("*") if f.is_file()]
    return sum(f.stat().st_size for f in files) / 1e6''',
           '''def du(path):
    """Size of a file or directory tree in MB: local files plus the same path on HDFS (Dataproc)."""
    p = Path(path)
    files = [p] if p.is_file() else [f for f in p.rglob("*") if f.is_file()]
    local = sum(f.stat().st_size for f in files) / 1e6
    try:
        r = subprocess.run(["hdfs", "dfs", "-du", "-s", str(p)], capture_output=True, text=True, timeout=60)
        hdfs = int(r.stdout.split()[0]) / 1e6 if r.returncode == 0 and r.stdout.strip() else 0.0
    except (OSError, ValueError, subprocess.TimeoutExpired):
        hdfs = 0.0
    return local + hdfs''')

# ---- environment table: CPU model on Linux, cluster description --------------------------------
replace_in("def _sh(*cmd):",
           '''    ("CPU", _sh("sysctl", "-n", "machdep.cpu.brand_string") if sys.platform == "darwin" else platform.processor()),''',
           '''    ("CPU", _sh("sysctl", "-n", "machdep.cpu.brand_string") if sys.platform == "darwin"
            else _sh("sh", "-c", "grep -m1 'model name' /proc/cpuinfo | cut -d: -f2")),
    ("cluster", os.environ.get("CLUSTER_DESC", "")),''')

# ---- drop Section 20 (laptop core benchmark) --------------------------------------------------
drop = [i for i, c in enumerate(cells) if text(c).startswith("## 20. Scalability")
        or text(c).startswith("# --- 20. Scalability benchmark") or text(c).startswith("# --- 20b. Laptop vs Dataproc")]
assert len(drop) == 3, drop
note = {"cell_type": "markdown", "id": "dataproc20", "metadata": {}, "source": [
    "## 20. Scalability\n", "\n",
    "Omitted in the Dataproc run: Section 20 times the cleaning job in `local[n]` sessions on one machine. The laptop\n",
    "results are in the submitted notebook, and the cluster's 2- and 4-worker timings of the same job are in\n",
    "`outputs/tables/cloud/t43_cloud_scaling.csv`.\n"]}
cells[drop[0]] = note
for i in sorted(drop[1:], reverse=True):
    del cells[i]

# ---- title: say where this copy ran --------------------------------------------------------------
title = cells[0]
s = text(title)
marker = "This single notebook is the complete project"
assert marker in s
set_text(title, s.replace(marker, (
    "> **Dataproc execution.** This copy was generated by `cloud/make_dataproc_notebook.py` from the submitted\n"
    "> notebook and executed on a Google Cloud Dataproc cluster (YARN, HDFS). The analysis code is identical; only the\n"
    "> Spark master, the storage (HDFS) and Section 20 differ (see the generator's docstring).\n\n" + marker), 1))

# ---- strip outputs and write -------------------------------------------------------------------
for c in cells:
    if c["cell_type"] == "code":
        c["outputs"], c["execution_count"] = [], None
        compile(text(c), "<cell>", "exec")
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(json.dumps(nb, indent=1, ensure_ascii=False) + "\n")
print(f"wrote {OUT.relative_to(REPO)}: {sum(c['cell_type'] == 'code' for c in cells)} code cells")
